export function drawRainbowUnicorn(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
): void {
  for (const layer of rainbowUnicornLayers) {
    drawBitmap(ctx, layer.bitmap, x, y, layer.color);
  }
}
